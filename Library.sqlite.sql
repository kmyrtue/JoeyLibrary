/*
  SQLite version of Library.sql.
  Create the database file with:  sqlite3 library.db < Library.sqlite.sql

  Differences from the Postgres version:
  - "INT GENERATED BY DEFAULT AS IDENTITY" becomes "INTEGER PRIMARY KEY" (auto-numbered).
  - SQLite has no BOOLEAN or DATE types: booleans are 0/1 integers, dates are
    'YYYY-MM-DD' text, which sorts correctly and works with date() / strftime().
  - DECIMAL becomes REAL, so NumberInSeries can hold values like 2.5.
  - SQLite has no DROP ... CASCADE, so tables are dropped children-first.
  - Foreign keys are only enforced when each connection runs
    "PRAGMA foreign_keys = ON;" (the application must do this when it connects).
*/

PRAGMA foreign_keys = ON;

DROP TABLE IF EXISTS BooksWishedAuthors;
DROP TABLE IF EXISTS BooksWishedGenres;
DROP TABLE IF EXISTS BooksWished;
DROP TABLE IF EXISTS BooksOwnedAuthors;
DROP TABLE IF EXISTS BooksOwnedGenres;
DROP TABLE IF EXISTS BooksOwned;
DROP TABLE IF EXISTS Series;
DROP TABLE IF EXISTS Formats;
DROP TABLE IF EXISTS Authors;
DROP TABLE IF EXISTS Genres;

CREATE TABLE Genres (
    GenreID INTEGER PRIMARY KEY,
    GenreName VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE Authors (
    AuthorID INTEGER PRIMARY KEY,
    AuthorName VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE Formats (
    FormatID INTEGER PRIMARY KEY,
    FormatName VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE Series (
    SeriesID INTEGER PRIMARY KEY,
    SeriesName VARCHAR(255) NOT NULL UNIQUE
);


/* Owned books sql */
CREATE TABLE BooksOwned (
    BookID  INTEGER PRIMARY KEY,
    Title   VARCHAR(255) NOT NULL,
    Edition VARCHAR(100),
    LoanedTo VARCHAR(255),
    LoanedDate TEXT,                                   -- 'YYYY-MM-DD'
    Rating INTEGER CHECK (Rating >= 0 AND Rating <= 5),
    Comments TEXT,
    Format INTEGER REFERENCES Formats(FormatID),
    ShelfNumber INTEGER,
    NumberInSeries REAL,
    SeriesName INTEGER REFERENCES Series(SeriesID),
    Signed INTEGER CHECK (Signed IN (0, 1)),
    EdgeOut INTEGER CHECK (EdgeOut IN (0, 1)),
    Read INTEGER CHECK (Read IN (0, 1)),
    StartedDate TEXT,                                  -- 'YYYY-MM-DD'
    FinishedDate TEXT,                                 -- 'YYYY-MM-DD'
    PageCount INTEGER,
    ISBN VARCHAR(20)
);


/* Table to link genres with books (many-to-many relationship) */
CREATE TABLE BooksOwnedGenres (
    BookID INTEGER,
    GenreID INTEGER,
    PRIMARY KEY (BookID, GenreID),
    FOREIGN KEY (BookID) REFERENCES BooksOwned(BookID) ON DELETE CASCADE,
    FOREIGN KEY (GenreID) REFERENCES Genres(GenreID) ON DELETE CASCADE
);

/* Table to link authors and co-authors with books (many-to-many relationship) */
CREATE TABLE BooksOwnedAuthors (
    BookID INTEGER,
    AuthorID INTEGER,
    PRIMARY KEY (BookID, AuthorID),
    FOREIGN KEY (BookID) REFERENCES BooksOwned(BookID) ON DELETE CASCADE,
    FOREIGN KEY (AuthorID) REFERENCES Authors(AuthorID) ON DELETE CASCADE
);


/* Wished books sql */
CREATE TABLE BooksWished (
    BookID  INTEGER PRIMARY KEY,
    Title   VARCHAR(255) NOT NULL,
    Edition VARCHAR(100),
    Format INTEGER REFERENCES Formats(FormatID),
    NumberInSeries REAL,
    SeriesName INTEGER REFERENCES Series(SeriesID),
    Signed INTEGER CHECK (Signed IN (0, 1)),
    ISBN VARCHAR(20)
);

/* Table to link genres with books (many-to-many relationship) */
CREATE TABLE BooksWishedGenres (
    BookID INTEGER,
    GenreID INTEGER,
    PRIMARY KEY (BookID, GenreID),
    FOREIGN KEY (BookID) REFERENCES BooksWished(BookID) ON DELETE CASCADE,
    FOREIGN KEY (GenreID) REFERENCES Genres(GenreID) ON DELETE CASCADE
);

/* Table to link authors and co-authors with books (many-to-many relationship) */
CREATE TABLE BooksWishedAuthors (
    BookID INTEGER,
    AuthorID INTEGER,
    PRIMARY KEY (BookID, AuthorID),
    FOREIGN KEY (BookID) REFERENCES BooksWished(BookID) ON DELETE CASCADE,
    FOREIGN KEY (AuthorID) REFERENCES Authors(AuthorID) ON DELETE CASCADE
);
