


DROP TABLE IF EXISTS Genres CASCADE;
CREATE TABLE Genres (
    GenreID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    GenreName VARCHAR(100) NOT NULL UNIQUE
);

/* Free-text labels the user makes up, used like genres */
DROP TABLE IF EXISTS Tags CASCADE;
CREATE TABLE Tags (
    TagID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TagName VARCHAR(100) NOT NULL UNIQUE
);

DROP TABLE IF EXISTS Authors CASCADE;
CREATE TABLE Authors (
    AuthorID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    AuthorName VARCHAR(255) NOT NULL UNIQUE
);

DROP TABLE IF EXISTS Formats CASCADE;
CREATE TABLE Formats (
    FormatID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FormatName VARCHAR(100) NOT NULL UNIQUE
);

DROP TABLE IF EXISTS Series CASCADE;
CREATE TABLE Series (
    SeriesID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SeriesName VARCHAR(255) NOT NULL UNIQUE
);


/* Owned books sql */
DROP TABLE IF EXISTS BooksOwned CASCADE;
CREATE TABLE BooksOwned (
    BookID  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Title   VARCHAR(255) NOT NULL,
    Edition VARCHAR(100),
    LoanedTo VARCHAR(255),
    LoanedDate DATE,
    Rating INT CHECK (Rating >= 0 AND Rating <= 5),
    Spice INT CHECK (Spice >= 0 AND Spice <= 5),
    Kink INT CHECK (Kink >= 0 AND Kink <= 5),
    Comments TEXT,
    Format INT REFERENCES Formats(FormatID),
    ShelfNumber INT,
    NumberInSeries DECIMAL,
    SeriesName INT REFERENCES Series(SeriesID),
    Signed BOOLEAN,
    EdgeOut BOOLEAN,
    Read BOOLEAN,                                      -- the dates of each reading are in ReadingHistory
    PageCount INT,
    ISBN VARCHAR(20)
);


/* Table to link genres with books (many-to-many relationship) */
DROP TABLE IF EXISTS BooksOwnedGenres CASCADE;
CREATE TABLE BooksOwnedGenres (
    BookID INT,
    GenreID INT,
    PRIMARY KEY (BookID, GenreID),
    FOREIGN KEY (BookID) REFERENCES BooksOwned(BookID) ON DELETE CASCADE,
    FOREIGN KEY (GenreID) REFERENCES Genres(GenreID) ON DELETE CASCADE
);

/* Table to link authors and co-authors with books (many-to-many relationship) */
DROP TABLE IF EXISTS BooksOwnedAuthors CASCADE;
CREATE TABLE BooksOwnedAuthors (
    BookID INT,
    AuthorID INT,
    PRIMARY KEY (BookID, AuthorID),
    FOREIGN KEY (BookID) REFERENCES BooksOwned(BookID) ON DELETE CASCADE,
    FOREIGN KEY (AuthorID) REFERENCES Authors(AuthorID) ON DELETE CASCADE
);







